@dataclass
class ContainerSpec:
    namespace: str
    parent_path: str
    name: str
    focus: str
    signals: str
    goal: str
    impact: str
    method: str = "synthesizes"
    value_type: str = "ordinal"
    tags: Optional[List[str]] = None
    sensitive: bool = False

    def build_container(self) -> dict:
        if self.tags is None:
            namespace_tag = self.namespace.lower()
            self.tags = [namespace_tag, "stage2"]

        if self.parent_path == self.namespace:
            path = f"{self.namespace}.{self.name}"
        else:
            path = f"{self.parent_path}.{self.name}"

        container = {
            "id": f"{path}.v1",
            "namespace": self.namespace,
            "path": path,
            "version": 1,
            "status": "prototype",
            "description": self.build_description(),
            "inputs": [],
            "outputs": [],
            "ucn_weight_hint": 0.01,
            "dependencies": [],
            "correlates_with": [],
            "contradicts": [],
            "sensitive": self.sensitive,
            "camouflage": False,
            "consent_required": self.sensitive,
            "ai_upgradable": True,
            "rr_baseline": None,
            "curiosity_baseline": 100,
            "discovery": DISCOVERY,
            "parent_containers": [
                {
                    "path": self.parent_path,
                    "edge_type": "part_of",
                }
            ],
            "tags": self.tags,
            "examples": [],
            "validation_rules": {
                "value_type": self.value_type,
            },
            "created_at": TIMESTAMP,
            "updated_at": TIMESTAMP,
            "created_by": CREATED_BY,
            "changelog": [
                {
                    "version": 1,
                    "timestamp": TIMESTAMP,
                    "changes": "Initial creation during Stage 2 pilot expansion",
                    "author": CREATED_BY,
                }
            ],
        }
        return container

    def build_description(self) -> str:
        sentences = [
            f"This container examines {self.focus}.",
            f"It {self.method} evidence from {self.signals} to {self.goal}.",
            f"These insights {self.impact}.",
        ]
        description = " ".join(s.strip() for s in sentences)
        word_count = len(description.split())
        if not (20 <= word_count <= 100):
            raise ValueError(
                f"Description for {self.namespace}.{self.name} has {word_count} words"
            )
        return description


def gather_existing_paths() -> set[str]:
    data = json.loads(REGISTRY_PATH.read_text())
    return {c["path"] for c in data["containers"]}


def validate_specs(specs: List[ContainerSpec], existing_paths: set[str]) -> None:
    seen_paths = set()
    for spec in specs:
        path = f"{spec.namespace}.{spec.name}" if spec.parent_path == spec.namespace else f"{spec.parent_path}.{spec.name}"
        if path in existing_paths:
            raise ValueError(f"Path already exists: {path}")
        if path in seen_paths:
            raise ValueError(f"Duplicate new path: {path}")
        parent = spec.parent_path
        if parent not in existing_paths:
            raise ValueError(f"Parent path missing: {parent} for {path}")
        seen_paths.add(path)


def write_patch(containers: List[dict]) -> None:
    PATCH_PATH.write_text(json.dumps({"containers": containers}, indent=2))


def write_cross_links(edges: List[dict]) -> None:
    lines = ["edges:"]
    for edge in edges:
        lines.append(f"  - from: {edge['from']}")
        lines.append(f"    to: {edge['to']}")
        lines.append(f"    type: {edge['type']}")
        if edge.get("evidence"):
            lines.append(f"    evidence: {edge['evidence']}")
        lines.append(f"    confidence: {edge['confidence']}")
    CROSS_LINKS_PATH.write_text("\n".join(lines) + "\n")


